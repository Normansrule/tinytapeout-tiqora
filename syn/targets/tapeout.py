def gen_core_rtl(world: dict, t: dict) -> str:
    """The carrier's hard macro: frame-native pins around the plain macro.

    Every inversion and constant lives here, inside the macro, because the
    frame wrappers are elaborated without standard cells."""
    c = t["carrier"]
    fr = world["frames"][c["frame"]]
    n = pad_count(world, c["frame"])
    macro_files = core_sources(world) + t["design"].get("files", [])
    mports = module_ports(world, macro_files, c["macro"])
    pins = sorted(c["pins"], key=lambda p: p["pad"])
    cpad = clock_pad(t)
    openframe = "pad_dm" in fr

    L = [f"// {c['core']}.sv — {GENERATED.format(src=t['_file'])}",
         "//",
         f"// {t['summary']}",
         f"// Frame: {fr['description']}, {fr['repo']} at {fr['commit'][:7]}.",
         "//",
         "//   pad  role  signal",
         ]
    if cpad is not None:
        L.append(f"//   {cpad:>3}  in    clock")
    for p in pins:
        role = pin_role(p)
        desc = p.get("in", "") if role == "in" else p["out"]
        if role == "io":
            desc = f"{p['out']} / {p['in']}"
        if "oe" in p:
            desc += f" (enable {p['oe']})"
        L.append(f"//   {p['pad']:>3}  {role:<4}  {desc}")
    L += ["`default_nettype none", "", f"module {c['core']} (",
          "`ifdef USE_POWER_PINS",
          f"    inout  wire        {fr['power']['vdd']},",
          f"    inout  wire        {fr['power']['gnd']},",
          "`endif"]
    decl = [f"    input  wire        {s}" for s in fr["core_inputs"]]
    decl.append(f"    input  wire [{n-1}:0] {fr['pad_in']}")
    decl.append(f"    output wire [{n-1}:0] {fr['pad_out']}")
    decl.append(f"    output wire [{n-1}:0] {fr['pad_oeb']}")
    if openframe:
        decl += [f"    output wire [{n-1}:0] gpio_inp_dis",
                 f"    output wire [{n-1}:0] gpio_dm2",
                 f"    output wire [{n-1}:0] gpio_dm1",
                 f"    output wire [{n-1}:0] gpio_dm0"]
    L.append(",\n".join(decl))
    L.append(");")

    # wires for every macro port
    clk_sig = f"{fr['pad_in']}[{cpad}]" if cpad is not None else c["clock"]
    terms = []
    for term in c["reset_n"]:
        inv = term.startswith("!")
        terms.append(("~" if inv else "") + term.lstrip("!"))
    L.append("")
    L.append("    // the macro's pins, prefixed m_ so they cannot clash with frame names")
    for name, (d, w) in mports.items():
        if name in ("clk", "rst_n"):
            continue
        rng = f"[{w-1}:0] " if w > 1 else ""
        L.append(f"    wire {rng}m_{name};")
    L.append(f"    wire m_rst_n = {' & '.join(terms)};")
    L.append("")
    L.append(f"    {c['macro']} u_macro (")
    L.append("`ifdef USE_POWER_PINS")
    L.append(f"        .vccd1({fr['power']['vdd']}),")
    L.append(f"        .vssd1({fr['power']['gnd']}),")
    L.append("`endif")
    conns = []
    for name in mports:
        if name == "clk":
            conns.append(f"        .clk({clk_sig})")
        else:
            conns.append(f"        .{name}(m_{name})")
    L.append(",\n".join(conns))
    L.append("    );")
    L.append("")

    used = {p["pad"]: p for p in pins}
    if cpad is not None:
        used[cpad] = {"pad": cpad, "in": None}
    unused_in = []
    for pad in range(n):
        p = used.get(pad)
        pi, po, po_e = fr["pad_in"], fr["pad_out"], fr["pad_oeb"]
        reads_pad = pad == cpad or (p is not None and bool(p.get("in")))
        if not reads_pad:
            unused_in.append(f"{pi}[{pad}]")
        if p is None:
            role = "unused"
            out, oeb = "1'b0", "1'b1"
        else:
            role = pin_role(p) if p.get("in", "") is not None else "in"
            m = lambda sig: "m_" + sig
            if role == "out" and "oe" in p:
                out, oeb = m(p["out"]), f"~{m(p['oe'])}"
            elif role == "out":
                out, oeb = m(p["out"]), "1'b0"
            elif role == "io":
                out, oeb = m(p["out"]), f"~{m(p['oe'])}"
            else:
                out, oeb = "1'b0", "1'b1"
            if p.get("in"):
                L.append(f"    assign {m(p['in'])} = {pi}[{pad}];")
        L.append(f"    assign {po}[{pad}] = {out};")
        L.append(f"    assign {po_e}[{pad}] = {oeb};")
        if openframe:
            key = "out" if (role == "out") else role
            dm = fr["pad_dm"][key]
            L.append(f"    assign {{gpio_dm2[{pad}], gpio_dm1[{pad}], gpio_dm0[{pad}]}} = 3'b{dm:03b};")
            L.append(f"    assign gpio_inp_dis[{pad}] = 1'b{fr['pad_inp_dis'][key]};")
    L.append("")
    if unused_in:
        L.append("    wire _unused = &{1'b0, " + ", ".join(unused_in) + ", 1'b0};")
    L.append(f"endmodule : {c['core']}")
    return "\n".join(L) + "\n"


def frame_port_decl(world: dict, frame: str) -> list[str]:
    fp = world["frame_ports"][frame]
    lines, power = [], []
    for p in fp["ports"]:
        rng = f"[{p['msb']}:{p['lsb']}] " if p["msb"] != p["lsb"] or p.get("vector") else ""
        s = f"    {p['dir']:<6} wire {rng}{p['name']}"
        (power if p.get("power") else lines).append(s)
    return power, lines


def gen_wrapper_rtl(world: dict, t: dict) -> str:
    """The fixed frame wrapper: wiring only, exactly the upstream ports."""
    c = t["carrier"]
    fr = world["frames"][c["frame"]]
    fp = world["frame_ports"][c["frame"]]
    power, sig = frame_port_decl(world, c["frame"])
    L = [f"// {fr['module']}.sv — {GENERATED.format(src=t['_file'])}",
         "//",
         f"// The fixed {c['frame']} wrapper ({fr['repo']} {fr['file']} at {fr['commit'][:7]}),",
         f"// with {c['core']} as its only content. Wiring only: the frame flow",
         "// elaborates this level without standard cells.",
         "//",
         "// The port list is the frame's and cannot change, so frame inputs this",
         "// design does not read and frame outputs it does not drive are expected:",
         "// the waivers below cover exactly those two lint classes, in this file.",
         "`default_nettype none", "",
         "/* verilator lint_off UNUSEDSIGNAL */",
         "/* verilator lint_off UNUSEDPARAM */",
         "/* verilator lint_off UNDRIVEN */"]
    head = f"module {fr['module']}"
    if fp.get("params"):
        head += f" #({fp['params']})"
    L.append(head + " (")
    L.append("`ifdef USE_POWER_PINS")
    L.append(",\n".join(power) + ",")
    L.append("`endif")
    L.append(",\n".join(sig))
    L.append(");")
    n = pad_count(world, c["frame"])
    conns = []
    conns.append("`ifdef USE_POWER_PINS")
    conns.append(f"        .{fr['power']['vdd']}({fr['power']['vdd']}),")
    conns.append(f"        .{fr['power']['gnd']}({fr['power']['gnd']}),")
    conns.append("`endif")
    body = [f"        .{s}({s})" for s in fr["core_inputs"]]
    body += [f"        .{fr['pad_in']}({fr['pad_in']})",
             f"        .{fr['pad_out']}({fr['pad_out']})",
             f"        .{fr['pad_oeb']}({fr['pad_oeb']})"]
    if "pad_dm" in fr:
        body += ["        .gpio_inp_dis(gpio_inp_dis)", "        .gpio_dm2(gpio_dm2)",
                 "        .gpio_dm1(gpio_dm1)", "        .gpio_dm0(gpio_dm0)"]
    L.append(f"    {c['core']} {c['instance']} (")
    L += conns
    L.append(",\n".join(body))
    L.append("    );")
    for s in fr.get("loopback_zero", []):
        L.append(f"    assign {s} = gpio_loopback_zero;")
    L.append(f"endmodule : {fr['module']}")
    L.append("/* verilator lint_on UNDRIVEN */")
    L.append("/* verilator lint_on UNUSEDPARAM */")
    L.append("/* verilator lint_on UNUSEDSIGNAL */")
    L.append("`default_nettype wire")
    return "\n".join(L) + "\n"


def gen_user_defines(world: dict, t: dict) -> str:
    c = t["carrier"]
    fr = world["frames"][c["frame"]]
    n = pad_count(world, c["frame"])
    used = {p["pad"]: pin_role(p) for p in c["pins"]}
    for p in c["pins"]:
        if pin_role(p) == "out" and "oe" in p:
            used[p["pad"]] = "io"
    L = [f"// user_defines.v — {GENERATED.format(src=t['_file'])}",
         "//",
         "// Power-on mode of each Caravel GPIO for this design. Copy over",
         "// caravel_user_project/verilog/rtl/user_defines.v; the mode values",
         "// are that file's own definitions.",
         "`default_nettype none", "`ifndef __USER_DEFINES_H", "`define __USER_DEFINES_H", ""]
    up = Path(__file__).parent / "caravel_gpio_modes.vh"
    L.append(up.read_text().rstrip())
    L.append("")
    for pad in range(fr["gpio_mode_first"], n):
        mode = fr["gpio_modes"][used.get(pad, "unused")]
        L.append(f"`define USER_CONFIG_GPIO_{pad}_INIT{' ' * (3 - len(str(pad)))}`{mode}")
    L += ["", "`endif // __USER_DEFINES_H"]
    return "\n".join(L) + "\n"


def ll_common(world: dict, t: dict, design: str, die: list, files: list[str]) -> dict:
    pdk = world["pdks"][t["pdk"]]
    d = t["design"]
    cfg = {
        "//": GENERATED.format(src=t["_file"]),
        "DESIGN_NAME": design,
        "VERILOG_FILES": [f"dir::../../{f}" for f in files],
        "CLOCK_PORT": d.get("clock_port", "clk"),
        "CLOCK_PERIOD": d["clock_period_ns"],
        "IO_DELAY_CONSTRAINT": d.get("io_delay_pct", 20),
        "FP_SIZING": "absolute",
        "DIE_AREA": [0, 0, die[0], die[1]],
        "PL_TARGET_DENSITY_PCT": t["floorplan"]["density_pct"],
        "VDD_NETS": [t.get("power", pdk["default_power"])["vdd"]],
        "GND_NETS": [t.get("power", pdk["default_power"])["gnd"]],
        "RUN_LINTER": 1,
        "RUN_MAGIC_DRC": 1,
        "RUN_KLAYOUT_DRC": 1,
        "RUN_LVS": 1,
    }
    cfg.update(pdk.get("librelane", {}))   # PDK settings LibreLane lacks
    cfg.update(t.get("librelane", {}))
    return cfg


def gen_configs(world: dict, t: dict) -> dict[str, str]:
    """{relative path: text} of every LibreLane config the target needs."""
    k = t["kind"]
    out = {}
    if k == "macro":
        cfg = ll_common(world, t, t["design"]["top"], t["floorplan"]["die_um"],
                        target_sources(world, t))
        out[f"targets/{t['_stem']}/config.json"] = json.dumps(cfg, indent=4) + "\n"
    elif k == "carrier":
        c = t["carrier"]
        fr = world["frames"][c["frame"]]
        tc = dict(t)
        tc["power"] = fr["power"]
        core = ll_common(world, tc, c["core"], t["floorplan"]["die_um"],
                         target_sources(world, t))
        if clock_pad(t) is not None:
            core["CLOCK_PORT"] = f"{fr['pad_in']}[{clock_pad(t)}]"
        else:
            core["CLOCK_PORT"] = c["clock"]
        out[f"targets/{t['_stem']}/core.json"] = json.dumps(core, indent=4) + "\n"
        run = "dir::runs/core/final"
        cc = c["core"]
        wr = {
            "//": GENERATED.format(src=t["_file"]),
            "DESIGN_NAME": fr["module"],
            "VERILOG_FILES": [f"dir::../../{wrapper_rtl_path(world, t)}"],
            "CLOCK_PORT": core["CLOCK_PORT"] if clock_pad(t) is None else f"{fr['pad_in']}[{clock_pad(t)}]",
            "CLOCK_NET": f"{c['instance']}.u_macro.clk",
            "CLOCK_PERIOD": t["design"]["clock_period_ns"],
            "FP_SIZING": "absolute",
            "DIE_AREA": [0, 0, fr["die_um"][0], fr["die_um"][1]],
            "FP_DEF_TEMPLATE": f"dir::../.upstream/{c['frame']}/{fr['def_template']}",
            "SYNTH_ELABORATE_ONLY": 1,
            "VERILOG_POWER_DEFINE": "USE_POWER_PINS",
            "VDD_NETS": fr["wrapper_vdd_nets"],
            "GND_NETS": fr["wrapper_gnd_nets"],
            "PDN_MACRO_CONNECTIONS": [f"{c['instance']} {fr['power']['vdd']} {fr['power']['gnd']} {fr['power']['vdd']} {fr['power']['gnd']}"],
            "MACROS": {cc: {
                "gds": [f"{run}/gds/{cc}.gds"],
                "lef": [f"{run}/lef/{cc}.lef"],
                "nl": [f"{run}/nl/{cc}.nl.v"],
                "pnl": [f"{run}/pnl/{cc}.pnl.v"],
                "spef": {f"{rc}_*": [f"{run}/spef/{rc}/{cc}.{rc}.spef"] for rc in ("min", "nom", "max")},
                "instances": {c["instance"]: {"location": c["location_um"], "orientation": "N"}},
            }},
            "RUN_CTS": 0,
            "RUN_FILL_INSERTION": 0,
            "RUN_TAP_ENDCAP_INSERTION": 0,
            "PDN_ENABLE_RAILS": 0,
            "RUN_LINTER": 0,
            "RUN_MAGIC_DRC": 1,
            "RUN_KLAYOUT_DRC": 1,
            "RUN_LVS": 1,
            "MAGIC_ZEROIZE_ORIGIN": 0,
        }
        wr.update(fr["wrapper_librelane"])
        wr.update(t.get("wrapper_librelane", {}))
        out[f"targets/{t['_stem']}/wrapper.json"] = json.dumps(wr, indent=4) + "\n"
    return out


def generated_files(world: dict) -> dict[str, str]:
    out = {}
    for t in world["targets"].values():
        out.update(gen_configs(world, t))
        if t.get("kind") == "carrier":
            out[core_rtl_path(t)] = gen_core_rtl(world, t)
            out[wrapper_rtl_path(world, t)] = gen_wrapper_rtl(world, t)
            if "gpio_modes" in world["frames"][t["carrier"]["frame"]]:
                out[f"targets/{t['_stem']}/user_defines.v"] = gen_user_defines(world, t)
    out["targets/STATUS.md"] = gen_status(world)
    return out


