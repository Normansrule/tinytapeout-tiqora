def liberty(pdk_root: Path, pdk_name: str, pdk: dict, pvt: str) -> Path:
    scl = pdk["scl"]
    return pdk_root / pdk_name / "libs.ref" / scl / "lib" / f"{scl}__{pvt}.lib"


def synth_top(world: dict, t: dict) -> tuple[str, list[str]]:
    if t["kind"] == "carrier":
        return t["carrier"]["core"], target_sources(world, t)
    return t["design"]["top"], target_sources(world, t)


def build_dir(t: dict) -> Path:
    d = ROOT / "targets" / ".build" / t["_stem"]
    d.mkdir(parents=True, exist_ok=True)
    return d


def run_synth(world: dict, t: dict, pdk_root: Path, label: str) -> dict:
    pdk = world["pdks"][t["pdk"]]
    lib = liberty(pdk_root, t["pdk"], pdk, pdk["lib_pvt"]["tt"])
    if not lib.exists():
        raise SystemExit(f"no liberty at {lib}")
    top, files = synth_top(world, t)
    bd = build_dir(t)
    period_ps = int(t["design"]["clock_period_ns"] * 1000)
    rel = lambda p: os.path.relpath(p, ROOT)
    # Cells the target's LibreLane run may not use are marked dont_use, so
    # the area is the one place and route starts from.
    lib_used = lib
    excl = t.get("librelane", {}).get("SYNTH_EXCLUDED_CELL_FILE")
    if excl:
        excl_path = (ROOT / "targets" / t["_stem"] / excl.replace("dir::", "")).resolve()
        lib_used = bd / "lib_dont_use.lib"
        mark_dont_use(lib, excl_path, lib_used)
    reads = "\n".join(f"read_verilog -sv {f}" for f in files)
    ys = f"""{reads}
hierarchy -check -top {top}
synth -top {top} -flatten
dfflibmap -liberty {rel(lib_used)}
abc -D {period_ps} -liberty {rel(lib_used)} -script {rel(bd / 'abc.script')}
hilomap -singleton -hicell {pdk['tie']['hi']} -locell {pdk['tie']['lo']}
opt_clean -purge
tee -o {rel(bd / 'stat.txt')} stat -liberty {rel(lib_used)}
write_verilog -noattr -noexpr -nohex -nodec {rel(bd / 'netlist.v')}
"""
    # Timing-driven mapping with fanout buffering (max fanout from the PDK
    # limits), as place and route would add: without it one reset inverter
    # drives every flip-flop and the timing is meaningless.
    fo = pdk["limits"]["max_fanout"]
    (bd / "abc.script").write_text(
        f"strash; dch; map -D {period_ps}; topo; stime -c; "
        f"buffer -c -N {fo}; upsize -c -D {period_ps}; dnsize -c -D {period_ps}; stime -p\n")
    (bd / "synth.ys").write_text(ys)
    yosys = shutil.which("yosys")
    r = subprocess.run([yosys, "-q", "-s", rel(bd / "synth.ys")], cwd=ROOT,
                       capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(f"yosys failed:\n{r.stderr[-3000:]}")
    stat = (bd / "stat.txt").read_text()
    area = float(re.search(r"Chip area for (?:top )?module.*?:\s*([\d.]+)", stat).group(1))
    cells = int(re.search(r"Number of cells:\s*(\d+)", stat).group(1))
    flops = sum(int(n) for c, n in re.findall(r"^\s+(\S*(?:df|dl)\S*)\s+(\d+)\s*$", stat, re.M)
                if re.search(r"__(s?df|dfx|dfr|dfs|dfb|dfrtp|dfstp|dfxtp|dfrbp|sdf)", c) or "dff" in c.lower())
    ver = subprocess.run([yosys, "-V"], capture_output=True, text=True).stdout.strip().split(" (")[0]
    w, h = t["floorplan"]["die_um"]
    return {
        "tool": ver, "pdk_label": label, "liberty": lib.name,
        "command": f"python3 syn/targets/tapeout.py synth {t['_stem']} --pdk-root $PDK_ROOT",
        "top": top, "area_um2": round(area, 1), "cells": cells, "flops": flops,
        "util_pct": round(100.0 * area / (w * h), 2),
    }


def mark_dont_use(lib: Path, excl: Path, out: Path):
    pats = [l.strip() for l in excl.read_text().splitlines()
            if l.strip() and not l.lstrip().startswith("#")]
    rx = [re.compile("^" + p.replace("*", ".*") + "$") for p in pats]
    res = []
    for line in lib.read_text().splitlines(keepends=True):
        res.append(line)
        m = re.match(r'\s*cell\s*\(\s*"?([A-Za-z0-9_]+)"?\s*\)\s*\{', line)
        if m and any(r.match(m.group(1)) for r in rx):
            res.append("    dont_use : true;\n")
    out.write_text("".join(res))


def run_sta(world: dict, t: dict, pdk_root: Path) -> dict:
    pdk = world["pdks"][t["pdk"]]
    top, _ = synth_top(world, t)
    bd = build_dir(t)
    nl = bd / "netlist.v"
    if not nl.exists():
        raise SystemExit("run `synth` first")
    sta = shutil.which("sta") or os.environ.get("STA_BIN")
    if not sta:
        raise SystemExit("OpenSTA (`sta`) is needed; set STA_BIN")
    P = t["design"]["clock_period_ns"]
    io = t["design"].get("io_delay_pct", 20) / 100.0
    clk = t["design"].get("clock_port", "clk")
    if t["kind"] == "carrier":
        fr = world["frames"][t["carrier"]["frame"]]
        clk = f"{fr['pad_in']}[{clock_pad(t)}]" if clock_pad(t) is not None else t["carrier"]["clock"]
    corners = {}
    for tag in ("tt", "ss", "ff"):
        pvt = pdk["lib_pvt"][tag]
        lib = liberty(pdk_root, t["pdk"], pdk, pvt)
        tcl = f"""read_liberty {lib}
read_verilog {nl}
link_design {top}
create_clock -name clk -period {P} [get_ports {{{clk}}}]
set_clock_uncertainty 0.25 [get_clocks clk]
set ins [delete_from_list [all_inputs] [get_ports {{{clk}}}]]
set_input_delay {P * io:.4f} -clock clk $ins
set_output_delay {P * io:.4f} -clock clk [all_outputs]
set_driving_cell -lib_cell {pdk['driving_cell']['cell']} -pin {pdk['driving_cell']['pin']} $ins
set_load {pdk['output_load_pf']} [all_outputs]
puts "SETUP [sta::format_time [sta::worst_slack_cmd max] 4]"
puts "HOLD [sta::format_time [sta::worst_slack_cmd min] 4]"
set p [find_timing_paths -from [all_registers -clock_pins] -to [all_registers -data_pins] -path_delay max -group_path_count 1]
foreach path $p {{ puts "R2R [sta::format_time [$path slack] 4] [sta::format_time [$path data_required_time] 4] [sta::format_time [$path data_arrival_time] 4]" }}
report_checks -path_delay max -format full -digits 3 > {bd}/sta_{tag}_max.rpt
exit
"""
        (bd / f"sta_{tag}.tcl").write_text(tcl)
        r = subprocess.run([sta, "-no_init", "-no_splash", "-exit", str(bd / f"sta_{tag}.tcl")],
                           capture_output=True, text=True)
        txt = r.stdout + r.stderr
        try:
            setup = float(re.search(r"^SETUP\s+(-?[\d.]+)", txt, re.M).group(1))
            hold = float(re.search(r"^HOLD\s+(-?[\d.]+)", txt, re.M).group(1))
            s2, req, arr = (float(x) for x in re.search(r"^R2R\s+(-?[\d.]+)\s+(-?[\d.]+)\s+(-?[\d.]+)", txt, re.M).groups())
        except AttributeError:
            raise SystemExit(f"OpenSTA output not understood:\n{txt[-3000:]}")
        # the register-to-register path delay the clock must cover: the
        # period minus the slack of the worst such path
        corners[f"nom_{pvt}"] = {"setup_ws_ns": round(setup, 3), "hold_ws_ns": round(hold, 3),
                                 "reg2reg_ns": round(P - s2, 3)}
    ver = subprocess.run([sta, "-version"], capture_output=True, text=True).stdout.strip()
    return {"tool": f"OpenSTA {ver}", "period_ns": P, "io_delay_pct": int(io * 100),
            "command": f"python3 syn/targets/tapeout.py sta {t['_stem']} --pdk-root $PDK_ROOT",
            "corners": corners}


