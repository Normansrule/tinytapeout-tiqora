def tt_target(world: dict) -> dict:
    tts = [t for t in world["targets"].values() if t.get("kind") == "tinytapeout"]
    if len(tts) != 1:
        raise SystemExit("exactly one target must have kind = \"tinytapeout\"")
    return tts[0]


def core_sources(world: dict) -> list[str]:
    """The shared RTL core: the Tiny Tapeout source list minus its top."""
    info = world["info"]
    top = info.get("top_module", "")
    out = []
    for f in info["source_files"]:
        text = read_file(world, f"src/{f}") or ""
        if re.search(rf"^\s*module\s+{re.escape(top)}\b", text, re.M):
            continue
        out.append(f"src/{f}")
    return out


def target_sources(world: dict, t: dict) -> list[str]:
    files = list(core_sources(world))
    files += t.get("design", {}).get("files", [])
    if t.get("kind") == "carrier":
        files.append(core_rtl_path(t))
    return files


def core_rtl_path(t: dict) -> str:
    return f"src/targets/{t['carrier']['core']}.sv"


def wrapper_rtl_path(world: dict, t: dict) -> str:
    return f"src/targets/{world['frames'][t['carrier']['frame']]['module']}.sv"


def bit(sig: str) -> tuple[str, int | None]:
    m = re.fullmatch(r"([A-Za-z_][A-Za-z0-9_]*)(?:\[(\d+)\])?", sig.strip())
    if not m:
        raise ValueError(f"bad signal name {sig!r}")
    return m.group(1), (int(m.group(2)) if m.group(2) is not None else None)


def pad_count(world: dict, frame: str) -> int:
    fr = world["frames"][frame]
    for p in world["frame_ports"][frame]["ports"]:
        if p["name"] == fr["pad_in"]:
            return p["msb"] - p["lsb"] + 1
    raise KeyError(frame)


def pin_role(pin: dict) -> str:
    if "in" in pin and "out" in pin:
        return "io"
    if "out" in pin:
        return "out"
    return "in"


def clock_pad(t: dict) -> int | None:
    m = re.fullmatch(r"pad\s+(\d+)", t["carrier"]["clock"])
    return int(m.group(1)) if m else None


