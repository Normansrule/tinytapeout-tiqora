def gates(world: dict, t: dict, metrics: dict, stage: str = "core") -> list[tuple[str, str, bool, str]]:
    """[(gate, what, passed, detail)] for one finished LibreLane run.

    A metric that is missing fails its gate: an unreported number is not a
    passing one."""
    s = t["signoff"]
    pdk = world["pdks"][t["pdk"]]
    rows = []

    def need(key):
        return metrics.get(key)

    def row(g, what, ok, detail):
        rows.append((g, what, bool(ok), detail))

    # G1 setup / G2 hold, every corner
    for kind, g, floor in (("setup", "G1", s.get("setup_min_ns", 0.0)),
                           ("hold", "G2", s.get("hold_min_ns", 0.0))):
        for cn in pdk["corners"]:
            v = need(f"timing__{kind}__ws__corner:{cn}")
            r2r = need(f"timing__{kind}_r2r__ws__corner:{cn}")
            note = "" if r2r is None else f", flop to flop {r2r:+.3f}"   # shows whether a pin path is the worst
            row(g, f"{kind} slack {cn}", v is not None and v >= floor,
                "missing" if v is None else f"{v:+.3f} ns (floor {floor:+.2f}{note})")
    # G3 physical verification
    for key, what in (("route__drc_errors", "router DRC"),
                      ("magic__drc_error__count", "Magic DRC"),
                      ("klayout__drc_error__count", "KLayout DRC"),
                      ("magic__illegal_overlap__count", "illegal overlaps"),
                      ("design__lvs_error__count", "LVS errors"),
                      ("antenna__violating__nets", "antenna nets")):
        v = need(key)
        row("G3", what, v == 0, "missing" if v is None else str(v))
    # G4 electrical limits, every corner
    for key, what, allow in (("design__max_slew_violation__count", "max slew", s.get("max_slew", 0)),
                             ("design__max_cap_violation__count", "max capacitance", s.get("max_cap", 0)),
                             ("design__max_fanout_violation__count", "max fanout", s.get("max_fanout", 0))):
        for cn in pdk["corners"]:
            v = need(f"{key}__corner:{cn}")
            row("G4", f"{what} {cn}", v is not None and v <= allow,
                "missing" if v is None else f"{v} (allowed {allow})")
    # G5 netlist integrity
    for key, what in (("design__instance_unmapped__count", "unmapped cells"),
                      ("synthesis__check_error__count", "synthesis check errors"),
                      ("design__power_grid_violation__count", "power grid violations")):
        v = need(key)
        if stage == "wrapper" and key != "design__power_grid_violation__count":
            continue
        row("G5", what, v == 0, "missing" if v is None else str(v))
    # G6 utilisation
    if stage == "core":
        v = need("design__instance__utilization")
        cap = s.get("max_util_pct", 70) / 100.0
        row("G6", "placed utilisation", v is not None and v <= cap,
            "missing" if v is None else f"{100*v:.1f}% (cap {100*cap:.0f}%)")
    return rows


def passing_metrics(world: dict, t: dict) -> dict:
    """A metrics.json that passes every gate: the mutants' starting point."""
    m = {}
    for cn in world["pdks"][t["pdk"]]["corners"]:
        m[f"timing__setup__ws__corner:{cn}"] = 1.0
        m[f"timing__hold__ws__corner:{cn}"] = 0.2
        for k in ("slew", "cap", "fanout"):
            m[f"design__max_{k}_violation__count__corner:{cn}"] = 0
    for k in ("route__drc_errors", "magic__drc_error__count", "klayout__drc_error__count",
              "magic__illegal_overlap__count", "design__lvs_error__count", "antenna__violating__nets",
              "design__instance_unmapped__count", "synthesis__check_error__count",
              "design__power_grid_violation__count"):
        m[k] = 0
    m["design__instance__utilization"] = 0.40
    return m


