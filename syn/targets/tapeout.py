REQUIRED = {
    "tinytapeout": ["name", "kind", "summary", "pdk", "tiles", "design"],
    "macro": ["name", "kind", "summary", "pdk", "design", "floorplan", "signoff"],
    "carrier": ["name", "kind", "summary", "pdk", "design", "floorplan", "carrier", "signoff"],
}


def check(world: dict, verbose=False) -> list[str]:
    errs: list[str] = []

    def e(rule, msg):
        errs.append(f"{rule}  {msg}")

    pdks, frames = world["pdks"], world["frames"]
    ll = set(world["ll_vars"]["current"])
    dep = set(world["ll_vars"]["deprecated"])

    # T1
    for name, t in world["targets"].items():
        k = t.get("kind")
        if k not in REQUIRED:
            e("T1", f"{name}: unknown kind {k!r}")
            continue
        for key in REQUIRED[k]:
            if key not in t:
                e("T1", f"{name}: missing {key!r}")
        if t.get("name") != name:
            e("T1", f"{name}: name = {t.get('name')!r} must equal the file name")
        if t.get("pdk") not in pdks:
            e("T1", f"{name}: unknown pdk {t.get('pdk')!r}")
        if k in ("macro", "carrier"):
            for key in ("clock_period_ns",):
                if key not in t.get("design", {}):
                    e("T1", f"{name}: design.{key} missing")
            if k == "macro" and "top" not in t.get("design", {}):
                e("T1", f"{name}: design.top missing")
    if errs:
        return errs

    # T2
    core = core_sources(world)
    if not core:
        e("T2", "info.yaml lists no core sources")
    for name, t in world["targets"].items():
        if t["kind"] == "tinytapeout":
            continue
        srcs = target_sources(world, t)
        if srcs[:len(core)] != core:
            e("T2", f"{name}: does not build the shared core first ({srcs[:3]} ...)")
        for f in srcs:
            if read_file(world, f) is None and f not in generated_names(world):
                e("T2", f"{name}: source {f} does not exist")

    # T3
    tt = tt_target(world)
    info, cfg = world["info"], world["tt_config"]
    if tt["design"].get("top") != info.get("top_module"):
        e("T3", f"{tt['name']}: top {tt['design'].get('top')!r} != info.yaml {info.get('top_module')!r}")
    if tt.get("tiles") != info.get("tiles"):
        e("T3", f"{tt['name']}: tiles {tt.get('tiles')!r} != info.yaml {info.get('tiles')!r}")
    if float(tt["design"].get("clock_period_ns", -1)) != float(cfg.get("CLOCK_PERIOD", -2)):
        e("T3", f"{tt['name']}: clock {tt['design'].get('clock_period_ns')} ns != src/config.json {cfg.get('CLOCK_PERIOD')}")
    hz = info.get("clock_hz")
    if hz and abs(1e9 / float(hz) - float(tt["design"].get("clock_period_ns", 0))) > 1e-6:
        e("T3", f"{tt['name']}: clock {tt['design'].get('clock_period_ns')} ns != info.yaml clock_hz {hz}")

    # T4
    for name, t in world["targets"].items():
        if t["kind"] != "carrier":
            continue
        c = t["carrier"]
        if c.get("frame") not in frames:
            e("T4", f"{name}: unknown frame {c.get('frame')!r}")
            continue
        fr = frames[c["frame"]]
        if t["pdk"] != fr["pdk"]:
            e("T4", f"{name}: pdk {t['pdk']} but frame {c['frame']} is {fr['pdk']}")
        n = pad_count(world, c["frame"])
        seen = {}
        cpad = clock_pad(t)
        if cpad is not None:
            seen[cpad] = "clock"
        elif c["clock"] not in fr["core_inputs"]:
            e("T4", f"{name}: clock {c['clock']!r} is neither 'pad N' nor a frame input {fr['core_inputs']}")
        for term in c.get("reset_n", []):
            if term.lstrip("!") not in fr["core_inputs"]:
                e("T4", f"{name}: reset term {term!r} is not a frame input")
        macro_files = core_sources(world) + t["design"].get("files", [])
        try:
            mports = module_ports(world, macro_files, c["macro"])
        except RuntimeError as ex:
            e("T4", f"{name}: {ex}")
            continue
        driven = {}
        for p in c["pins"]:
            pad = p.get("pad")
            if not isinstance(pad, int) or not 0 <= pad < n:
                e("T4", f"{name}: pad {pad!r} outside 0..{n-1}")
                continue
            if pad in fr["reserved_pads"]:
                e("T4", f"{name}: pad {pad} is reserved by the frame")
            if pad in seen:
                e("T4", f"{name}: pad {pad} used twice ({seen[pad]} and {p})")
            seen[pad] = p
            for kind in ("in", "out", "oe"):
                if kind not in p:
                    continue
                try:
                    base, idx = bit(p[kind])
                except ValueError as ex:
                    e("T4", f"{name}: {ex}")
                    continue
                if base not in mports:
                    e("T4", f"{name}: pad {pad}: {base} is not a port of {c['macro']}")
                    continue
                d, w = mports[base]
                want = "input" if kind == "in" else "output"
                if d != want:
                    e("T4", f"{name}: pad {pad}: {p[kind]} is an {d}, used as {kind}")
                if (idx is None and w != 1) or (idx is not None and idx >= w):
                    e("T4", f"{name}: pad {pad}: {p[kind]} is not a bit of {base}[{w-1}:0]")
                key = (base, idx if idx is not None else 0)
                if kind == "in":
                    if key in driven:
                        e("T4", f"{name}: {p[kind]} driven from two pads")
                    driven[key] = pad
                else:
                    driven.setdefault(("out", key), pad)
        for base, (d, w) in mports.items():
            if base in ("clk", "rst_n") or base in (fr["power"]["vdd"], fr["power"]["gnd"]):
                continue
            for i in range(w):
                if d == "input" and (base, i) not in driven:
                    e("T4", f"{name}: macro input {base}[{i}] has no pad")
                if d == "output" and ("out", (base, i)) not in driven:
                    e("T4", f"{name}: macro output {base}[{i}] reaches no pad")
        if cpad is not None and any(q.get("pad") == cpad for q in c["pins"]):
            e("T4", f"{name}: clock pad {cpad} is also in the pin list")
        if "clk" not in mports or "rst_n" not in mports:
            e("T4", f"{name}: {c['macro']} needs clk and rst_n ports")

    # T5
    if not errs:
        try:
            gen = generated_files(world)
        except Exception as ex:  # a broken target can break generation
            e("T5", f"generation failed: {ex}")
            gen = {}
        for rel, text in gen.items():
            have = read_file(world, rel)
            if have != text:
                e("T5", f"{rel} is stale: run `python3 syn/targets/tapeout.py generate`")

    # T6
    for name, t in world["targets"].items():
        if t["kind"] == "tinytapeout":
            continue
        for rel, text in gen_configs(world, t).items():
            for key in json.loads(text):
                if key == "//":
                    continue
                if key in dep:
                    e("T6", f"{rel}: {key} is a deprecated name in LibreLane {LIBRELANE_VERSION}")
                elif key not in ll:
                    e("T6", f"{rel}: {key} is not a LibreLane {LIBRELANE_VERSION} variable")

    # T7
    for name, t in world["targets"].items():
        if t["kind"] != "carrier" or errs:
            continue
        c = t["carrier"]
        fr = frames[c["frame"]]
        rel = wrapper_rtl_path(world, t)
        files = target_sources(world, t) + [rel]
        try:
            got = module_ports(world, files, fr["module"], defines=("USE_POWER_PINS",))
        except RuntimeError as ex:
            e("T7", f"{name}: {ex}")
            continue
        want = {p["name"]: (p["dir"], p["msb"] - p["lsb"] + 1)
                for p in world["frame_ports"][c["frame"]]["ports"]}
        if got != want:
            missing = sorted(set(want) - set(got))
            extra = sorted(set(got) - set(want))
            diff = sorted(k for k in set(got) & set(want) if got[k] != want[k])
            e("T7", f"{name}: {fr['module']} ports differ from {fr['repo']}@{fr['commit'][:7]}: "
                    f"missing {missing}, extra {extra}, changed {diff}")

    # T8
    for name, t in world["targets"].items():
        r = world["results"].get(name, {}).get("synth")
        if not r or t["kind"] == "tinytapeout":
            continue
        w, h = t["floorplan"]["die_um"]
        util = 100.0 * r["area_um2"] / (w * h)
        cap = t["floorplan"]["max_util_pct"]
        if util > cap:
            e("T8", f"{name}: cells {r['area_um2']:,.0f} um2 = {util:.1f}% of the {w:g} x {h:g} die, over the {cap}% cap")
    return errs


def generated_names(world: dict) -> set[str]:
    names = set()
    for t in world["targets"].values():
        if t.get("kind") == "carrier":
            names.add(core_rtl_path(t))
            names.add(wrapper_rtl_path(world, t))
    return names


