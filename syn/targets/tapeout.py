def mutants(world: dict) -> int:
    base_errs = check(world)
    if base_errs:
        print("check fails before mutation; fix that first:")
        for x in base_errs:
            print("  " + x)
        return 1
    cases = []
    tts = tt_target(world)
    macros = [t for t in world["targets"].values() if t["kind"] == "macro"]
    carriers = [t for t in world["targets"].values() if t["kind"] == "carrier"]

    def mut(name, rule, fn):
        cases.append((name, rule, fn))

    def edit_target(stem, f):
        def go(w):
            f(w["targets"][stem])
        return go

    m0 = macros[0]["_stem"]
    mut("T1 missing floorplan", "T1", edit_target(m0, lambda t: t.pop("floorplan")))
    mut("T1 unknown pdk", "T1", edit_target(m0, lambda t: t.__setitem__("pdk", "sky90")))
    mut("T1 name mismatch", "T1", edit_target(m0, lambda t: t.__setitem__("name", "other")))
    mut("T2 macro drops a core file", "T2",
        lambda w: w["info"]["source_files"].append("core/does_not_exist.sv"))
    mut("T3 tiles drift", "T3", edit_target(tts["_stem"], lambda t: t.__setitem__("tiles", "8x2")))
    mut("T3 clock drift", "T3", lambda w: w["tt_config"].__setitem__("CLOCK_PERIOD", 25))
    mut("T3 top drift", "T3", lambda w: w["info"].__setitem__("top_module", "tt_um_other"))
    if carriers:
        c0 = carriers[0]["_stem"]

        def first_pin(t):
            return t["carrier"]["pins"][0]
        mut("T4 pad out of range", "T4", edit_target(c0, lambda t: first_pin(t).__setitem__("pad", 99)))
        fr0 = world["frames"][carriers[0]["carrier"]["frame"]]
        if fr0["reserved_pads"]:
            mut("T4 reserved pad", "T4", edit_target(c0, lambda t: first_pin(t).__setitem__("pad", fr0["reserved_pads"][0])))
        mut("T4 pad used twice", "T4", edit_target(c0, lambda t: t["carrier"]["pins"][1].__setitem__("pad", first_pin(t)["pad"])))
        mut("T4 macro input unconnected", "T4", edit_target(c0, lambda t: t["carrier"]["pins"].pop(0)))
        mut("T4 output used as input", "T4", edit_target(c0, lambda t: first_pin(t).__setitem__("in", t["carrier"]["pins"][-1].get("out", "nope"))))
        mut("T4 unknown macro port", "T4", edit_target(c0, lambda t: first_pin(t).__setitem__("in", "no_such_port[0]")))
        mut("T4 bit out of range", "T4", edit_target(c0, lambda t: first_pin(t).__setitem__("in", re.sub(r"\[\d+\]", "[63]", first_pin(t)["in"]))))
        mut("T4 reset from unknown signal", "T4", edit_target(c0, lambda t: t["carrier"].__setitem__("reset_n", ["!nobody"])))
        cof = [t for t in carriers if clock_pad(t) is not None]
        if cof:
            cc = cof[0]["_stem"]
            mut("T4 clock pad also a pin", "T4", edit_target(cc, lambda t: t["carrier"]["pins"].append({"pad": clock_pad(t), "in": "gpio_in[0]"})))
        rel = core_rtl_path(carriers[0])
        txt = read_file(world, rel)
        mut("T5 hand-edited carrier RTL", "T5", lambda w: w["files"].__setitem__(rel, txt.replace("1'b1;", "1'b0;", 1)))
        relw = wrapper_rtl_path(world, carriers[0])
        txtw = read_file(world, relw)
        # T7: drop one frame port from the wrapper text the check elaborates,
        # with T5 silenced by also editing the generator's view of the frame.
        def t7(w, relw=relw, txtw=txtw, frame=carriers[0]["carrier"]["frame"]):
            ports = w["frame_ports"][frame]["ports"]
            victim = next(p for p in ports if p["dir"] == "input" and not p.get("power")
                          and p["name"] not in w["frames"][frame]["core_inputs"]
                          and p["name"] != w["frames"][frame]["pad_in"])
            w["files"][relw] = re.sub(rf"^\s*input\s+wire\s+(\[[^\]]*\]\s+)?{victim['name']},?\n", "", txtw, flags=re.M)
            w["_skip_t5"] = True
        mut("T7 wrapper loses a frame port", "T7", t7)
    mut("T5 stale LibreLane config", "T5", edit_target(m0, lambda t: t["design"].__setitem__("clock_period_ns", 13.0)))
    mut("T6 unknown LibreLane variable", "T6", edit_target(m0, lambda t: t.setdefault("librelane", {}).__setitem__("NOT_A_VARIABLE", 1)))
    mut("T6 deprecated LibreLane variable", "T6", edit_target(m0, lambda t: t.setdefault("librelane", {}).__setitem__("FP_PDN_MULTILAYER", 0)))
    mut("T8 cells overflow the die", "T8", lambda w: w["results"].__setitem__(m0, {"synth": {"area_um2": 10.0 * w["targets"][m0]["floorplan"]["die_um"][0] * w["targets"][m0]["floorplan"]["die_um"][1]}}))

    killed = 0
    for name, rule, fn in cases:
        w = copy.deepcopy(world)
        fn(w)
        errs = check_for_mutant(w, rule)
        ok = any(x.startswith(rule) for x in errs)
        killed += ok
        print(f"  {'killed' if ok else 'SURVIVED'}  {name}" + ("" if ok else f"  (errors: {errs[:2]})"))

    # signoff gate mutants, on every hardenable target
    gate_cases = 0
    for t in macros + carriers:
        good = passing_metrics(world, t)
        rows = gates(world, t, good)
        if not all(r[2] for r in rows):
            print(f"  SURVIVED  {t['name']}: the all-pass metrics fail a gate")
            continue
        for key in sorted(good):
            for how in ("remove", "break"):
                m = dict(good)
                if how == "remove":
                    del m[key]
                elif "timing__" in key:
                    m[key] = -0.5
                elif "utilization" in key:
                    m[key] = 0.99
                else:
                    m[key] = 3
                gate_cases += 1
                if all(r[2] for r in gates(world, t, m)):
                    print(f"  SURVIVED  {t['name']}: gates pass with {key} {how}d")
                else:
                    killed += 1
    total = len(cases) + gate_cases
    print(f"mutants: {killed}/{total} killed ({len(cases)} check rules, {gate_cases} signoff-gate metrics)")
    return 0 if killed == total else 1


def rtl_mutants(world: dict) -> int:
    """Break target RTL one line at a time; the lockstep bench must fail."""
    spec_p = TARGETS / "_mutants.toml"
    if not spec_p.exists():
        print("no targets/_mutants.toml")
        return 1
    spec = load_toml(spec_p)
    bench = spec["bench"]
    cases = []
    for m in spec.get("mutant", []):
        cases.append((f"{m['file']}: {m['why']}", m["file"], m["find"], m["replace"]))
    for t in world["targets"].values():
        if t.get("kind") != "carrier":
            continue
        outs = [p for p in t["carrier"]["pins"] if pin_role(p) == "out" and "oe" not in p]
        if len(outs) < 2:
            continue
        w = copy.deepcopy(world)
        tt = w["targets"][t["_stem"]]
        a, b = [p for p in tt["carrier"]["pins"] if pin_role(p) == "out" and "oe" not in p][:2]
        a["out"], b["out"] = b["out"], a["out"]
        rel = core_rtl_path(t)
        cases.append((f"{rel}: pads {a['pad']} and {b['pad']} swapped in the pin map",
                      rel, None, gen_core_rtl(w, tt)))

    def run_bench():
        r = subprocess.run(bench, cwd=ROOT, capture_output=True, text=True)
        return r.returncode, r.stdout + r.stderr

    rc, out = run_bench()
    if rc:
        print("the bench fails before mutation:\n" + out[-2000:])
        return 1
    killed = 0
    for why, rel, find, repl in cases:
        p = ROOT / rel
        orig = p.read_text()
        if find is None:
            new = repl
        else:
            if orig.count(find) != 1:
                print(f"  BROKEN    {why}: text to replace found {orig.count(find)} times")
                continue
            new = orig.replace(find, repl)
        try:
            p.write_text(new)
            rc, out = run_bench()
        finally:
            p.write_text(orig)
        ok = rc != 0
        killed += ok
        print(f"  {'killed' if ok else 'SURVIVED'}  {why}")
    print(f"rtl mutants: {killed}/{len(cases)} killed")
    return 0 if killed == len(cases) else 1


def check_for_mutant(w: dict, rule: str) -> list[str]:
    _PORT_CACHE.clear()
    if w.pop("_skip_t5", False):
        # T7's mutant edits the wrapper text; let T5 not mask it.
        orig = generated_files
        try:
            globals()["generated_files"] = lambda world: {}
            return check(w)
        finally:
            globals()["generated_files"] = orig
    return check(w)


