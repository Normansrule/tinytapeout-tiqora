_PORT_CACHE: dict = {}


def module_ports(world: dict, files: list[str], top: str, defines=()) -> dict:
    """{name: (direction, width)} of `top`, elaborated by Yosys."""
    key = (tuple(files), top, tuple(defines),
           tuple((f, read_file(world, f)) for f in files if f in world["files"]))
    if key in _PORT_CACHE:
        return _PORT_CACHE[key]
    yosys = shutil.which("yosys") or shutil.which("yowasp-yosys")
    if not yosys:
        raise SystemExit("yosys is needed to read port lists (apt install yosys)")
    with tempfile.TemporaryDirectory(dir=ROOT) as td:
        reads = []
        for f in files:
            src = ROOT / f
            if f in world["files"]:
                src = Path(td) / Path(f).name
                src.write_text(world["files"][f])
            d = " ".join(f"-D{x}" for x in defines)
            reads.append(f"read_verilog -sv {d} {os.path.relpath(src, ROOT)}")
        out = os.path.relpath(Path(td) / "ports.json", ROOT)
        script = "; ".join(reads + [f"hierarchy -top {top}", "proc", f"write_json {out}"])
        r = subprocess.run([yosys, "-q", "-p", script], cwd=ROOT,
                           capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError(f"yosys could not elaborate {top}:\n{r.stderr[-2000:]}")
        js = json.loads((Path(td) / "ports.json").read_text())
    ports = {n: (p["direction"], len(p["bits"]))
             for n, p in js["modules"][top]["ports"].items()}
    _PORT_CACHE[key] = ports
    return ports


