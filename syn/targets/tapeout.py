def print_gates(rows) -> bool:
    ok = all(r[2] for r in rows)
    for g, what, passed, detail in rows:
        print(f"  {'PASS' if passed else 'FAIL'}  {g}  {what:<36} {detail}")
    print(f"signoff: {sum(r[2] for r in rows)}/{len(rows)} gates pass -> {'PASS' if ok else 'FAIL'}")
    return ok


def fetch_upstream(world: dict, t: dict):
    c = t["carrier"]
    fr = world["frames"][c["frame"]]
    d = TARGETS / ".upstream" / c["frame"]
    if not (d / ".git").exists():
        d.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "-q", "--filter=blob:none", fr["repo"], str(d)], check=True)
    subprocess.run(["git", "-C", str(d), "checkout", "-q", fr["commit"]], check=True)


def harden(world: dict, t: dict, extra: list[str]) -> int:
    stages = []
    if t["kind"] == "macro":
        stages = [("core", f"targets/{t['_stem']}/config.json")]
    elif t["kind"] == "carrier":
        fetch_upstream(world, t)
        stages = [("core", f"targets/{t['_stem']}/core.json"), ("wrapper", f"targets/{t['_stem']}/wrapper.json")]
    else:
        print("the Tiny Tapeout target hardens in .github/workflows/gds.yaml")
        return 1
    ok_all = True
    verdicts = {}
    for stage, cfg in stages:
        cmd = ["librelane", "--docker-no-tty", "--dockerized", "--pdk", t["pdk"],
               "--run-tag", stage, "--overwrite", cfg] + extra
        print("$ " + " ".join(cmd), flush=True)
        r = subprocess.run(cmd, cwd=ROOT)
        mp = ROOT / "targets" / t["_stem"] / "runs" / stage / "final" / "metrics.json"
        if not mp.exists():
            print(f"{stage}: LibreLane exited {r.returncode} and wrote no final/metrics.json")
            verdicts[stage] = f"FAIL (LibreLane exit {r.returncode}, no metrics)"
            ok_all = False
            break
        metrics = json.loads(mp.read_text())
        print(f"--- {stage} final/metrics.json ---")
        print(json.dumps(metrics, indent=1, sort_keys=True))
        print(f"--- {stage} signoff gates ---")
        ok = print_gates(gates(world, t, metrics, stage))
        verdicts[stage] = "PASS" if ok else "FAIL"
        ok_all &= ok and r.returncode == 0
    print("verdict: " + ", ".join(f"{k} {v}" for k, v in verdicts.items()))
    return 0 if ok_all else 1


