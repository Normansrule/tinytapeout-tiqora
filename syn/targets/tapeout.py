def load_toml(p: Path) -> dict:
    with open(p, "rb") as f:
        return tomllib.load(f)


def load_world() -> dict:
    """Everything check() looks at, as plain data, so mutants can edit it."""
    targets = {}
    for p in sorted(TARGETS.glob("*.toml")):
        if p.name.startswith("_"):      # _mutants.toml and other non-targets
            continue
        t = load_toml(p)
        t["_file"] = str(p.relative_to(ROOT))
        t["_stem"] = p.stem
        targets[p.stem] = t
    world = {
        "pdks": load_toml(FLOW / "pdks.toml"),
        "frames": load_toml(FLOW / "frames.toml"),
        "frame_ports": json.loads((FLOW / "frames.json").read_text())
                       if (FLOW / "frames.json").exists() else {},
        "ll_vars": json.loads((FLOW / "librelane_vars.json").read_text()),
        "targets": targets,
        "info": parse_info_yaml(ROOT / "info.yaml"),
        "tt_config": json.loads((ROOT / "src" / "config.json").read_text()),
        "results": {},
        "files": {},          # path -> text overrides (mutants)
    }
    if RESULTS.is_dir():
        for p in sorted(RESULTS.glob("*.json")):
            world["results"][p.stem] = json.loads(p.read_text())
    return world


def parse_info_yaml(p: Path) -> dict:
    """The few fields of info.yaml this tool needs, without a YAML library."""
    out = {"source_files": []}
    in_src = False
    for line in p.read_text().splitlines():
        s = line.split("#", 1)[0].rstrip()
        m = re.match(r"\s+(top_module|tiles|clock_hz):\s*\"?([^\"]+)\"?\s*$", s)
        if m:
            out[m.group(1)] = m.group(2).strip()
            in_src = False
            continue
        if re.match(r"\s+source_files:\s*$", s):
            in_src = True
            continue
        if in_src:
            m = re.match(r"\s+-\s*\"?([^\"]+)\"?\s*$", s)
            if m:
                out["source_files"].append(m.group(1).strip())
            elif s.strip():
                in_src = False
    return out


def read_file(world: dict, rel: str) -> str | None:
    if rel in world["files"]:
        return world["files"][rel]
    p = ROOT / rel
    return p.read_text() if p.exists() else None


