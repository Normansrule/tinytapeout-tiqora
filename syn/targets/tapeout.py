def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    sub.add_parser("check")
    sub.add_parser("generate")
    sub.add_parser("mutants")
    sub.add_parser("rtl-mutants")
    sub.add_parser("report")
    sub.add_parser("refresh-frames")
    for c in ("synth", "sta"):
        p = sub.add_parser(c)
        p.add_argument("target")
        p.add_argument("--pdk-root", default=os.environ.get("PDK_ROOT"))
        p.add_argument("--pdk-label", default="")
        p.add_argument("--no-save", action="store_true")
    p = sub.add_parser("signoff")
    p.add_argument("target")
    p.add_argument("metrics")
    p.add_argument("--stage", default="core", choices=["core", "wrapper"])
    p = sub.add_parser("harden")
    p.add_argument("target")
    p.add_argument("extra", nargs="*")
    a = ap.parse_args(argv)
    world = load_world()

    if a.cmd == "list":
        for n, t in world["targets"].items():
            print(f"{n:<18} {t['kind']:<12} {t['pdk']:<10} {t['summary']}")
        return 0
    if a.cmd == "check":
        errs = check(world)
        for x in errs:
            print("FAIL  " + x)
        n = len(world["targets"])
        print(f"tapeout check: {n} targets, rules T1-T8, {len(errs)} problems")
        return 1 if errs else 0
    if a.cmd in ("generate", "report"):
        for rel, text in generated_files(world).items():
            p = ROOT / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_text() != text:
                p.write_text(text)
                print(f"wrote {rel}")
        return 0
    if a.cmd == "mutants":
        return mutants(world)
    if a.cmd == "rtl-mutants":
        return rtl_mutants(world)
    if a.cmd == "refresh-frames":
        return refresh_frames(world)
    t = world["targets"].get(getattr(a, "target", ""))
    if t is None:
        print(f"unknown target; known: {', '.join(world['targets'])}")
        return 2
    if a.cmd in ("synth", "sta"):
        if t["kind"] == "tinytapeout":
            print("the Tiny Tapeout target is measured by syn/area_sky130.sh and the gds workflow")
            return 2
        if not a.pdk_root:
            print("pass --pdk-root (the directory holding sky130A/ or gf180mcuD/)")
            return 2
        root = Path(a.pdk_root)
        res_p = RESULTS / f"{t['_stem']}.json"
        res = json.loads(res_p.read_text()) if res_p.exists() else {}
        if a.cmd == "synth":
            res["synth"] = run_synth(world, t, root, a.pdk_label or str(root))
            res.pop("sta", None)   # a new netlist makes old timing stale
            print(json.dumps(res["synth"], indent=1))
        else:
            res["sta"] = run_sta(world, t, root)
            print(json.dumps(res["sta"], indent=1))
        if not a.no_save:
            RESULTS.mkdir(exist_ok=True)
            res_p.write_text(json.dumps(res, indent=1) + "\n")
        return 0
    if a.cmd == "signoff":
        metrics = json.loads(Path(a.metrics).read_text())
        return 0 if print_gates(gates(world, t, metrics, a.stage)) else 1
    if a.cmd == "harden":
        return harden(world, t, a.extra)
    return 2


if __name__ == "__main__":
    sys.exit(main())
