def parse_ports(text: str, module: str, defines: dict) -> dict:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    m = re.search(rf"module\s+{module}\s*(#\s*\((.*?)\))?\s*\((.*?)\)\s*;", text, re.S)
    if not m:
        raise SystemExit(f"module {module} not found")
    params = re.sub(r"\s+", " ", m.group(2)).strip() if m.group(2) else ""
    body = m.group(3)
    ports, power = [], False
    for raw in re.split(r"[,\n]", body):
        s = raw.strip()
        if not s:
            continue
        if s.startswith("`ifdef USE_POWER_PINS"):
            power = True
            continue
        if s.startswith("`endif"):
            power = False
            continue
        pm = re.fullmatch(r"(input|output|inout)\s+(?:wire\s+|reg\s+)?(?:\[([^\]:]+):([^\]]+)\]\s*)?([A-Za-z_]\w*)", s)
        if not pm:
            raise SystemExit(f"cannot parse port {s!r}")
        d, msb, lsb, name = pm.groups()

        def ev(x):
            x = x.strip()
            x = re.sub(r"`(\w+)", lambda m: str(defines[m.group(1)]), x)
            return int(eval(x, {"__builtins__": {}}))
        ports.append({"name": name, "dir": d,
                      "msb": ev(msb) if msb else 0, "lsb": ev(lsb) if lsb else 0,
                      "vector": msb is not None, "power": power})
    return {"params": params, "ports": ports}


def refresh_frames(world: dict) -> int:
    out = {}
    for name, fr in world["frames"].items():
        with tempfile.TemporaryDirectory() as td:
            def fetch(repo, commit, path):
                d = Path(td) / re.sub(r"\W", "_", repo)
                if not d.exists():
                    subprocess.run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", repo, str(d)], check=True)
                return subprocess.run(["git", "-C", str(d), "show", f"{commit}:{path}"],
                                      check=True, capture_output=True, text=True).stdout
            dtext = fetch(fr["defines_repo"], fr["defines_commit"], fr["defines_file"])
            defs = {}
            for k, v in re.findall(r"`define[ \t]+(\w+)[ \t]+([^\n/]+)", dtext):
                defs[k] = v.strip()
            for _ in range(4):
                for k in defs:
                    defs[k] = re.sub(r"`(\w+)", lambda m: f"({defs[m.group(1)]})" if m.group(1) in defs else m.group(0), defs[k])
            num = {}
            for k, v in defs.items():
                try:
                    num[k] = int(eval(v, {"__builtins__": {}}))
                except Exception:
                    pass
            text = fetch(fr["repo"], fr["commit"], fr["file"])
            got = parse_ports(text, fr["module"], num)
            got["source"] = f"{fr['repo']}/blob/{fr['commit']}/{fr['file']}"
            out[name] = got
    (FLOW / "frames.json").write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {FLOW / 'frames.json'}: " + ", ".join(f"{k} {len(v['ports'])} ports" for k, v in out.items()))
    return 0


