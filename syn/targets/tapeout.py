#!/usr/bin/env python3
"""tapeout.py — one RTL core, many tape-out targets.

Shared, byte-identical in tiqora-skywater130 and tinytapeout-tiqora
(docs/shared_flow.sha256). Each repo describes its targets in targets/*.toml;
this tool turns them into LibreLane 3.0.14 configurations and carrier
wrappers, checks them, synthesises them against the real cell libraries,
times them at every corner and applies the signoff gates to a finished run.

  tapeout.py list                      the targets and what each one is
  tapeout.py check                     every rule below, on every target
  tapeout.py generate                  rewrite the generated files
  tapeout.py mutants                   break each rule once, confirm check fails
  tapeout.py rtl-mutants               break target RTL (targets/_mutants.toml),
                                       confirm the lockstep bench fails
  tapeout.py synth  TARGET --pdk-root DIR [--pdk-label TEXT]
                                       Yosys + the PDK's typical library
  tapeout.py sta    TARGET --pdk-root DIR
                                       OpenSTA on that netlist, every corner
  tapeout.py signoff TARGET METRICS.json [--stage core|wrapper]
                                       the gates, on a LibreLane run
  tapeout.py harden TARGET             run LibreLane (--dockerized) + gates
  tapeout.py refresh-frames            re-extract frame port lists upstream
  tapeout.py report                    rewrite targets/STATUS.md

The rules `check` enforces (each one has a mutant in `mutants`):
  T1  every target file has the keys its kind needs, and names a known PDK
  T2  every non-Tiny-Tapeout target builds the same RTL core as the Tiny
      Tapeout target (info.yaml source_files minus its top)
  T3  the Tiny Tapeout target agrees with info.yaml and src/config.json
  T4  a carrier's pin map: pads exist, are not reserved, are used once,
      every macro port is connected, and the clock pad is an input
  T5  generated files (LibreLane configs, carrier RTL, user_defines.v,
      STATUS.md) match what this tool generates now
  T6  every LibreLane variable is a current LibreLane 3.0.14 name
      (librelane_vars.json, from the pinned wheel)
  T7  a generated wrapper's ports equal the pinned upstream frame's ports
  T8  synthesised cell area fits the die at the target's utilisation cap,
      when a synthesis result exists
"""
