#!/usr/bin/env python3
"""progress.py — the README's progress tracker, generated from docs/progress.json.

    python3 docs/tools/progress.py           rewrite the tracker in README.md
    python3 docs/tools/progress.py --check   fail if README.md is out of date or
                                             progress.json breaks a rule (make docs)

Each milestone is a list of steps. A step is "done", "doing", "todo" or
"blocked", and a step that is done or doing must carry its evidence:
"measured" with the version and the command that produced it. Nothing is
counted as done on an estimate. The bar is done steps out of all steps.
Edit docs/progress.json, never the generated block in README.md.
"""
import json, os, sys

BEGIN = "<!-- progress:begin (generated by docs/tools/progress.py from docs/progress.json; do not edit) -->"
END = "<!-- progress:end -->"
STATES = {"done": "✅", "doing": "🔄", "todo": "⬜", "blocked": "⛔"}


def problems(data):
    bad = []
    for ms in data["milestones"]:
        if not ms.get("steps"):
            bad.append(f"{ms['name']}: no steps")
        for st in ms.get("steps", []):
            where = f"{ms['name']} / {st.get('step', '?')}"
            if st.get("state") not in STATES:
                bad.append(f"{where}: state must be one of {', '.join(STATES)}")
                continue
            if st["state"] in ("done", "doing"):
                ev = st.get("evidence") or {}
                for k in ("label", "version", "command", "result"):
                    if not ev.get(k):
                        bad.append(f"{where}: {st['state']} needs evidence.{k}")
                if ev.get("label") and ev["label"] != "measured":
                    bad.append(f"{where}: evidence.label is '{ev['label']}'; only 'measured' counts")
            elif not st.get("next"):
                bad.append(f"{where}: {st['state']} needs 'next' (what moves it forward)")
    return bad


def bar(done, total, width=10):
    full = round(width * done / total)
    return "█" * full + "░" * (width - full)


def render(data):
    out = [BEGIN, "", "### Progress", ""]
    if data.get("note"):
        out += [data["note"], ""]
    out += ["| Milestone | Progress | Step | State | Evidence or next step |", "|---|---|---|---|---|"]
    for ms in data["milestones"]:
        steps = ms["steps"]
        done = sum(s["state"] == "done" for s in steps)
        for i, st in enumerate(steps):
            if st["state"] in ("done", "doing"):
                ev = st["evidence"]
                detail = f"{ev['result']}; measured ({ev['version']}, `{ev['command']}`)"
            else:
                detail = "next: " + st["next"]
            head = (f"**{ms['name']}**", f"`{bar(done, len(steps))}` {done}/{len(steps)}") if i == 0 else ("", "")
            out.append(f"| {head[0]} | {head[1]} | {st['step']} | {STATES[st['state']]} | {detail} |")
    out += ["", "✅ done · 🔄 in progress · ⬜ not started · ⛔ blocked. "
            "Only measured results count as done.", "", END]
    return "\n".join(out)


def main():
    root = os.getcwd()
    data = json.load(open(os.path.join(root, "docs", "progress.json")))
    bad = problems(data)
    readme = os.path.join(root, "README.md")
    text = open(readme).read()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        bad.append("README.md must hold exactly one progress block (the begin and end markers)")
    if bad:
        print("progress tracker:", *("  " + b for b in bad), sep="\n")
        sys.exit(1)
    a, b = text.index(BEGIN), text.index(END) + len(END)
    new = text[:a] + render(data) + text[b:]
    if "--check" in sys.argv:
        if new != text:
            print("progress tracker: README.md differs from docs/progress.json; "
                  "run python3 docs/tools/progress.py")
            sys.exit(1)
        n = sum(len(m["steps"]) for m in data["milestones"])
        print(f"progress tracker: {len(data['milestones'])} milestones, {n} steps, README.md up to date")
    else:
        open(readme, "w").write(new)
        print("README.md progress tracker rewritten")


if __name__ == "__main__":
    main()
